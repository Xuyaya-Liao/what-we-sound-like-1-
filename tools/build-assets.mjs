// build-assets.mjs: turns a dataset snapshot into the files the website uses.
//
// This runs on your computer with Node (not in the browser):
//     npm run build:assets
// or, to use a different snapshot folder:
//     npm run build:assets -- "path/to/snapshot"
//
// A "snapshot" is a folder exported by dataset-tools/curate.py. It contains
// images/, sounds/ and a manifest.csv describing every file (author, license, label…).
// Its default location is set in tools/lib/snapshot.mjs.
//
// What this script does:
//   1. Read the label table (config/labels.json), the exclusion list
//      (config/excluded.json) and the snapshot's manifest.csv
//   2. Check every row: not excluded, known label, allowed license, file exists
//   3. Copy the images into assets/images; even out the loudness of the sounds
//      and write them into assets/sounds
//   4. Write data/manifest.json, the one list the website reads

import fs from "node:fs";
import path from "node:path";
import { readWav, toMono, writeWav } from "./lib/wav.mjs";
import { normalizeLoudness } from "./lib/loudness.mjs";
import { EXCLUDED_FILE, PROJECT, readCsv, snapshotFolder } from "./lib/snapshot.mjs";

// ---- Where things are ----
const LABELS_FILE = path.join(PROJECT, "config/labels.json");
const ASSETS = path.join(PROJECT, "assets");
const OUTPUT = path.join(PROJECT, "data/manifest.json");

// Only these licenses may appear on a public website without asking anyone.
const LICENSE_NAMES = { "cc0": "CC0", "cc-by": "CC BY", "public-domain": "Public domain" };

// Loudness settings for the playback versions of the sounds (see tools/lib/loudness.mjs).
const LOUDNESS = {
  targetLufs: -23, // how loud every clip should feel (the broadcast standard)
  peakCeilingDb: -1, // no sample may go above this (0 would be the very top)
  maxBoostDb: 24, // never turn a very quiet clip up by more than this
};

// ---- 1. Read the inputs ----
const snapshot = snapshotFolder();
const rows = readCsv(path.join(snapshot, "manifest.csv"));
const { labels } = JSON.parse(fs.readFileSync(LABELS_FILE, "utf8"));
const labelIds = new Set(labels.map((label) => label.id));
const { excluded } = JSON.parse(fs.readFileSync(EXCLUDED_FILE, "utf8"));

console.log(`Snapshot: ${snapshot}`);
console.log(`${rows.length} rows in manifest.csv, ${labels.length} labels in config/labels.json`);

// ---- 2. Check every row and turn it into a clean entry ----
const images = [];
const sounds = [];
const skipped = [];

for (const row of rows) {
  const source = path.join(snapshot, row.file);
  const label = row.approved_label || row.search_label; // a human decision wins over the search term

  const exclusion = excluded[row.id] ?? excluded[row.source_id];
  if (exclusion) {
    skipped.push(`${row.id}: excluded in config/excluded.json (${exclusion})`);
    continue;
  }
  if (!LICENSE_NAMES[row.license]) {
    skipped.push(`${row.id}: license "${row.license}" is not allowed`);
    continue;
  }
  if (!fs.existsSync(source)) {
    skipped.push(`${row.id}: file missing (${row.file})`);
    continue;
  }
  if (row.kind === "image" && !labelIds.has(label)) {
    skipped.push(`${row.id}: label "${label}" is not in config/labels.json`);
    continue;
  }

  // Everything the credits page needs, plus where the file will live on the site.
  const folder = row.kind === "image" ? "images" : "sounds";
  const entry = {
    id: row.id,
    file: `assets/${folder}/${row.id}${path.extname(row.file).toLowerCase()}`,
    title: row.source_name,
    author: row.author || "Unknown",
    license: row.license,
    licenseName: LICENSE_NAMES[row.license],
    licenseUrl: row.license_url || row.source_url,
    sourceUrl: row.source_url,
    sourcePath: source, // remembered for copying, removed before writing the manifest
  };

  if (row.kind === "image") {
    images.push({ ...entry, label });
  } else if (row.kind === "sound") {
    sounds.push({
      ...entry,
      sourceId: row.source_id, // the original recording this clip was cut from
      category: label, // sounds are matched by how they sound, not by label; this is for reference
      startSec: Number(row.start_sec || 0), // where this 5-second clip starts in the original recording
      durationSec: Number(row.duration_sec || 0),
    });
  }
}

// ---- 3. Copy the files ----
// assets/images and assets/sounds are fully generated by this script,
// so they are emptied first. Nothing else in the project is touched.
for (const folder of ["images", "sounds"]) {
  fs.rmSync(path.join(ASSETS, folder), { recursive: true, force: true });
  fs.mkdirSync(path.join(ASSETS, folder), { recursive: true });
}

// Images: copied as they are.
for (const image of images) {
  fs.copyFileSync(image.sourcePath, path.join(PROJECT, image.file));
  delete image.sourcePath;
}

// Sounds: read, even out the loudness, write the playback version.
const loudnessNotes = {};
for (const [index, sound] of sounds.entries()) {
  process.stdout.write(`\rLoudness ${index + 1}/${sounds.length}`);
  const { sampleRate, channels } = readWav(sound.sourcePath);
  const result = normalizeLoudness(toMono(channels), sampleRate, LOUDNESS);
  writeWav(path.join(PROJECT, sound.file), result.samples, sampleRate);
  sound.originalLufs = round(result.loudness, 1); // how loud it was before
  sound.gainDb = round(result.gainDb, 1); // how much it was turned up (+) or down (-)
  (loudnessNotes[result.note] ??= []).push(sound.id);
  delete sound.sourcePath;
}
process.stdout.write("\n");

// ---- 4. Write data/manifest.json ----
const manifest = {
  generatedAt: new Date().toISOString(),
  snapshot: path.basename(snapshot),
  labels: labels.map((label) => ({
    ...label,
    imageCount: images.filter((image) => image.label === label.id).length,
  })),
  images,
  sounds,
};
fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
fs.writeFileSync(OUTPUT, JSON.stringify(manifest, null, 2) + "\n");

// ---- Report ----
console.log(`\nCopied ${images.length} images and ${sounds.length} sounds into assets/`);
console.log(`Wrote ${path.relative(PROJECT, OUTPUT)}`);
console.log(
  `Loudness (target ${LOUDNESS.targetLufs} LUFS): ` +
    Object.entries(loudnessNotes).map(([note, ids]) => `${ids.length} ${note}`).join(", "),
);
for (const note of ["peak-limited", "boost-capped", "silent"]) {
  if (!loudnessNotes[note]) continue;
  const quietest = sounds
    .filter((sound) => loudnessNotes[note].includes(sound.id))
    .map((sound) => sound.gainDb + sound.originalLufs)
    .sort((a, b) => a - b)[0];
  console.log(`  ${note}: these stay quieter than the target (quietest ends at ${quietest?.toFixed(1)} LUFS)`);
}
const thin = manifest.labels.filter((label) => label.imageCount < 5);
if (thin.length) {
  console.log(`Labels with fewer than 5 images: ${thin.map((l) => `${l.id} (${l.imageCount})`).join(", ")}`);
}
if (skipped.length) {
  console.log(`\nSkipped ${skipped.length} rows:`);
  for (const reason of skipped) console.log(`  - ${reason}`);
}

// ---- Helper: round a number to a few decimals ----
function round(value, decimals) {
  return Number.isFinite(value) ? Number(value.toFixed(decimals)) : null;
}
